/**
 * 把使用者打的職務收斂成正規職務。
 * 認不得就原樣回傳（**不吞掉**——通告單的「職位」常常寫的不是標準職務）。
 * 命中 null 規則＝那是組別或雜訊，回空字串。
 */
export function canonRole(label: string): string {
  const L = (label ?? "").trim().replace(/^[-－•‧*\s]+/, "");
  if (!L) return "";
  for (const [re, out] of CANON) if (re.test(L)) return out ?? "";
  return L;
}

/**
 * 副行要顯示的標準職稱，依語系。
 * zh＝英文（Armin 2026-08-30 驗收「自動英譯好滿」，別改）；ja＝日文業界標準詞；en＝英文。
 * 主行永遠是使用者自己打的字，這裡只是旁邊那行小字。
 */
export function roleAlt(canon: string, loc: string): string {
  return (loc === "ja" ? ROLE_JA[canon] : ROLE_EN[canon]) ?? "";
}

/** 依 ROLE_ORDER 排序用的名次；不在表裡的排最後。 */
export function roleRank(role: string): number {
  const i = ROLE_ORDER.indexOf(canonRole(role));
  return i < 0 ? ROLE_ORDER.length : i;
}
